import { describe, expect, it } from 'vitest'
import { casualReplyNeedsRewrite, casualReplyStatements } from '../server/contracts'

const experience = '对，抓住一下注意力就够了。我们继续随便聊，不整理、不加功能；我觉得做出来的小东西，比一大段介绍更有吸引力。'

describe('只聊感受的回合保留生活问题并收掉参数取舍', () => {
  it.each([
    ['嗯，就是那种不用太大声的回应，铃铛“叮”一下，你知道它在。你会喜欢偏小声的，还是稍微有点存在感的？', '嗯，就是那种不用太大声的回应，铃铛“叮”一下，你知道它在。'],
    ['这一小下回应就够了。你想用什么颜色？', '这一小下回应就够了。'],
    ['手指愿意再碰一下。你更喜欢大一点还是小一点的尺寸？', '手指愿意再碰一下。'],
    ['留一点空白很轻。要不要加一个声音开关？', '留一点空白很轻。'],
    ['页面要不要换成暖色？这个联想很安静。', '这个联想很安静。'],
    ['你希望亮度更强还是更弱？', ''],
    ['你想把速度调成多少？', ''],
    ['你想把音量调大吗', ''],
    ['你说的“声音要大一点吗？”像一个轻轻的念头。你想换成什么字体？', '你说的“声音要大一点吗？”像一个轻轻的念头。'],
    ['你更想用哪种文案？\n\n一点回应让手指知道它在。', '一点回应让手指知道它在。'],
  ])('只移除未被请求的参数问题 %s', (reply, expected) => {
    expect(casualReplyStatements(reply, true)).toBe(expected)
  })
  it.each([
    '你小时候也会摇桌上的小铃铛吗？',
    '你以前喜欢什么颜色的弹珠？',
    '你刚才听到的声音，是大声还是小声？',
    '你当时更喜欢亮一点的灯还是暗一点的灯？',
    '你会在什么时刻想顺手碰一下它？',
    '你平时有没有遇到过这种轻轻回应的小东西？',
    '声音轻轻应一下，不也挺好的吗？',
    '你说的“你会喜欢偏小声的，还是稍微有点存在感的？”是刚才那句。',
    '你说的「要不要加一个声音开关？」先只是被引用的问句。',
    '你会想起「声音」这个词吗？',
    '你会更喜欢“音量”这种比喻还是留白这种比喻？',
    '声音轻一点，留一小块空白，也能让人想碰一下。',
  ])('保留生活联想、引用和陈述 %s', reply => {
    expect(casualReplyStatements(reply, true)).toBe(reply)
  })
  it('原来的完全不追问模式仍移除生活问题', () => {
    expect(casualReplyStatements('那个小回应很轻。你小时候也摇过小铃铛吗？')).toBe('那个小回应很轻。')
  })
})

describe('明确陪聊回合的未询问技术附录', () => {
  it.each([
    '对，有个小东西在手里就更想试。\n\n现在这版代码里，强拍让第1和第5拍更醒目。',
    '亮一下就能抓住注意力。\n\n按这版代码，开关关掉时八拍均匀。',
    '你要关掉强拍试试，八拍就是均匀的八个点。',
    '这个完成感挺轻的。官方编译通过，真机还未验证。',
    '很容易上手。onHide 和 onUnload 都会清理。',
    '不用讲半天。源码中的方法是onBpm。',
    '这版本的第1和第5拍会更醒目。',
  ])('体验话题中的 %s 触发一次重写', reply => {
    expect(casualReplyNeedsRewrite(experience, reply)).toBe(true)
  })
  it.each([
    '做出来的小东西摆在那儿，确实比一段介绍更容易让人想碰一下。',
    '你平时有没有看到过什么小东西，眼睛一下就跟过去了？',
    '像走路踩地砖那样，身体先跟上了，没必要先想一个大目标。',
  ])('体验话题中的自然接话 %s 直接保留', reply => {
    expect(casualReplyNeedsRewrite(experience, reply)).toBe(false)
  })
  it.each([
    ['这版源码怎么处理离开页面？继续随便聊，不改作品', 'onHide 与 onUnload 清掉计时器，真机还没验收。'],
    ['继续聊体验，不改这轮。我刚刚试了强拍开关，关掉以后很均匀', '开关关掉时每一拍相同，你说的均匀感觉就是这个。'],
    ['代码如何实现？', '代码会先清理旧的计时器。'],
    ['就按这个做', '编程伙伴开始做，我们继续聊。'],
  ])('用户主动谈 %s 或未进入陪聊范围时保留回复', (text, reply) => {
    expect(casualReplyNeedsRewrite(text, reply)).toBe(false)
  })
  it('明确不要听代码说明时不把技术词当作用户提问', () => {
    expect(casualReplyNeedsRewrite('我们继续随便聊，暂时不改作品，不用讲代码', '代码里会清掉全部计时器。')).toBe(true)
  })
  it('引用里的技术词不能授权未被询问的代码附录', () => {
    expect(casualReplyNeedsRewrite('继续陪我聊感受，不改这轮。那句“代码”只是我刚才看到的一个词', '源码里有八拍计时器。')).toBe(true)
  })
})

describe('陪聊中的执行事实不跟随过时前提', () => {
  const lateExperience = '下一轮在界面选回薄荷了，正在做的这一版晴空不改。我们继续随便聊，不整理，也不加功能。三片叶子像给同一句话留一点空白。'
  const runningReplies = [
    '晴空这一版继续做着，不动它。你说的留一点空白很戳人。',
    '它还在做，我们可以继续聊翻面的感觉。',
    '编程伙伴正在编程，你刚说的空白挺轻的。',
    '这一版仍在制作，叶子像翻一张纸。',
    '这轮任务还在执行，不用催它。',
    '它还在写代码，你先聊感觉就好。',
    '晴空这版正在生成，我们慢慢聊。',
    '编程伙伴继续做着，三片叶子很安静。',
    '你放心，这版还在做，不会改这轮。',
  ]
  it.each(runningReplies)('没有运行中任务时重写过时说法 %s', reply => {
    expect(casualReplyNeedsRewrite(lateExperience, reply, false)).toBe(true)
  })
  it.each([
    '现在没有编程任务在运行。留一点空白，很像翻纸的感觉。',
    '这一版已经完成，下一轮卡选了薄荷。',
    '它已经不在做了，我们接着聊空白。',
    '不是它还在做，只是你刚才的话到得晚一点。',
    '你刚才说“它还在做”，像是等一张叶子慢慢展开。',
    '上一句“晴空这一版继续做着”已经过时了，叶子可以试了。',
    '如果它还在做，我们也可以聊别的。',
    '等下一轮开始，编程伙伴再继续做，我们先聊。',
    '下轮它继续做，我们先聊这种轻轻翻面的感觉。',
    '它还在做吗？我先看当前记录。',
    '过去编程伙伴正在编程，我们当时继续聊着。',
  ])('保留引用、否定、假设和下一轮语境 %s', reply => {
    expect(casualReplyNeedsRewrite(lateExperience, reply, false)).toBe(false)
  })
  it.each(runningReplies.slice(0, 5))('实际仍在运行时保留正常接话 %s', reply => {
    expect(casualReplyNeedsRewrite(lateExperience, reply, true)).toBe(false)
  })
})
